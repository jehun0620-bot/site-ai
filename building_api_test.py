import os
import requests
from dotenv import load_dotenv


# --------------------------------------------------
# 1. .env 파일 읽기
# --------------------------------------------------

load_dotenv()


# --------------------------------------------------
# 2. API 인증키 가져오기
# --------------------------------------------------

api_key = os.getenv("DATA_API_KEY")


if not api_key:
    print("ERROR: DATA_API_KEY를 찾을 수 없습니다.")
    exit()


print("API 인증키를 정상적으로 읽었습니다.")


# --------------------------------------------------
# 3. 건축HUB getBrTitleInfo 요청 URL
# --------------------------------------------------

url = "http://apis.data.go.kr/1613000/BldRgstHubService/getBrTitleInfo"


# --------------------------------------------------
# 4. PDF의 REST 요청 예제와 동일한 조건
# --------------------------------------------------

params = {
    "sigunguCd": "11680",
    "bjdongCd": "10300",
    "bun": "0012",
    "ji": "0000",
    "serviceKey": api_key,
}


# --------------------------------------------------
# 5. API 호출
# --------------------------------------------------

response = requests.get(
    url,
    params=params
)


# --------------------------------------------------
# 6. HTTP 상태 확인
# --------------------------------------------------

print()
print("HTTP 상태 코드:", response.status_code)


# --------------------------------------------------
# 7. 실제 요청된 URL 확인
# --------------------------------------------------

print()
print("실제로 요청된 URL:")
print(response.url)


# --------------------------------------------------
# 8. 서버 응답 확인
# --------------------------------------------------

print()
print("API 응답:")
print(response.text)